-- Soft duplicate detection used by the submission form to warn (never block).
create or replace function public.check_sighting_duplicate(
  p_common_name text,
  p_observed_at date,
  p_district text default null
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (
      select jsonb_build_object(
        'sighting_id', s.id,
        'status', s.status,
        'observed_at', s.observed_at,
        'common_name', s.common_name)
      from public.wildlife_sightings s
      where s.user_id = auth.uid()
        and s.status <> 'rejected'
        and s.observed_at = coalesce(p_observed_at, current_date)
        and lower(btrim(coalesce(s.common_name, ''))) = lower(btrim(coalesce(p_common_name, '')))
        and (p_district is null
             or lower(btrim(coalesce(s.district, ''))) = lower(btrim(coalesce(p_district, ''))))
      order by s.created_at desc
      limit 1
    ),
    'null'::jsonb);
$$;

-- Any authenticated reader can flag published content for moderation review.
-- Runs as definer so a reader never needs UPDATE rights on the sighting row.
create or replace function public.report_sighting(p_sighting_id uuid, p_reason text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_reason text := left(coalesce(nullif(btrim(coalesce(p_reason, '')), ''),
                                 'ব্যবহারকারীর রিপোর্ট'), 500);
begin
  if auth.uid() is null then
    raise exception 'লগইন আবশ্যক / Authentication required';
  end if;

  if not exists (
    select 1 from public.wildlife_sightings s
    where s.id = p_sighting_id and s.status = 'published' and s.is_published = true) then
    raise exception 'দর্শনটি পাওয়া যায়নি / Sighting not available';
  end if;

  perform set_config('earanyak.system_write', 'on', true);

  update public.wildlife_sightings
     set is_flagged = true, flag_reason = v_reason
   where id = p_sighting_id;

  insert into public.wildlife_sighting_audit_log
    (sighting_id, actor_id, actor_role, action, details)
  values (p_sighting_id, auth.uid(), 'user', 'user_report', jsonb_build_object('reason', v_reason));

  perform set_config('earanyak.system_write', 'off', true);
end;
$$;

-- Popular species (last 90 days) for the public "জনপ্রিয় প্রজাতি" section.
create or replace function public.popular_sighting_species(p_limit integer default 12)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(jsonb_agg(row_to_json(t)), '[]'::jsonb)
  from (
    select
      coalesce(nullif(btrim(coalesce(s.bengali_name, '')), ''),
               nullif(btrim(coalesce(s.common_name, '')), '')) as species,
      max(s.common_name) as common_name,
      max(s.scientific_name) as scientific_name,
      count(*) as sighting_count
    from public.wildlife_sightings s
    where s.status = 'published' and s.is_published = true
      and s.observed_at >= (current_date - interval '90 days')
    group by 1
    order by sighting_count desc, species asc
    limit greatest(1, least(coalesce(p_limit, 12), 30))
  ) t;
$$;

