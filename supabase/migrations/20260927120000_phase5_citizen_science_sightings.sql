-- Masking ladder: normal -> user/editor precision, elevated -> district,
-- high -> region, critical -> state only. Precise coordinates are NEVER public.
create or replace function public.effective_sighting_precision(
  p_precision text,
  p_sensitivity text
)
returns text
language sql
immutable
as $$
  select case
    when coalesce(p_sensitivity, 'normal') = 'critical' then 'hidden'
    when coalesce(p_sensitivity, 'normal') = 'high'
         and coalesce(p_precision, 'district') in ('precise_private', 'district')
      then 'region'
    when coalesce(p_precision, 'district') not in
         ('precise_private', 'district', 'region', 'hidden')
      then 'district'
    else coalesce(p_precision, 'district')
  end;
$$;

-- Bengali-first public location label built from the masked precision.
create or replace function public.build_public_location_label(
  p_district text,
  p_state text,
  p_country text,
  p_precision text,
  p_sensitivity text
)
returns text
language sql
immutable
as $$
  with parts as (
    select
      nullif(btrim(coalesce(p_district, '')), '') as district,
      nullif(btrim(coalesce(p_state, '')), '') as state,
      nullif(btrim(coalesce(p_country, '')), '') as country,
      public.effective_sighting_precision(p_precision, p_sensitivity) as precision
  )
  select case
    when (select district from parts) is null
         and (select state from parts) is null
         and (select country from parts) is null then null
    when (select precision from parts) = 'hidden'
      then coalesce((select state from parts), (select country from parts), 'ভারত')
    when (select district from parts) is null
      then coalesce((select state from parts), (select country from parts), 'ভারত')
    when (select precision from parts) = 'region'
      then (select district from parts) || '-এর কাছে, '
           || coalesce((select state from parts), (select country from parts), 'ভারত')
    else (select district from parts) || ' জেলা, '
         || coalesce((select state from parts), (select country from parts), 'ভারত')
  end;
$$;

-- Sensitivity inference from the IUCN status supplied by user/editor.
create or replace function public.infer_sighting_sensitivity(
  p_iucn text,
  p_current text
)
returns text
language sql
immutable
as $$
  select case
    when coalesce(p_current, 'normal') = 'critical' then 'critical'
    when lower(btrim(coalesce(p_iucn, ''))) in
         ('cr', 'en', 'vu', 'nt', 'critically endangered', 'endangered',
          'vulnerable', 'near threatened') then 'high'
    when coalesce(p_current, 'normal') = 'high' then 'high'
    when coalesce(p_current, 'normal') = 'elevated' then 'elevated'
    else 'normal'
  end;
$$;

-- Duplicate / near-duplicate fingerprint (species + day + place).
create or replace function public.build_sighting_content_hash(
  p_common_name text,
  p_bengali_name text,
  p_scientific_name text,
  p_observed_at date,
  p_district text
)
returns text
language sql
immutable
as $$
  select md5(
    lower(btrim(coalesce(p_scientific_name, ''))) || '|' ||
    lower(btrim(coalesce(p_common_name, ''))) || '|' ||
    lower(btrim(coalesce(p_bengali_name, ''))) || '|' ||
    coalesce(p_observed_at::text, '') || '|' ||
    lower(btrim(coalesce(p_district, '')))
  );
$$;

