create table if not exists public.wildlife_sightings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,

  -- lifecycle
  status text not null default 'draft'
    check (status in ('draft', 'submitted', 'under_review', 'needs_information',
                      'approved', 'published', 'rejected', 'archived')),
  submitted_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- species (user identification; editorial verification is a separate field)
  common_name text not null,
  bengali_name text,
  scientific_name text,
  description text,             -- Bengali observation description
  observation_notes text,
  iucn_status text,

  -- observation
  observed_at date not null default current_date,
  observed_time text,           -- approximate time, free text
  habitat text,
  individual_count integer
    check (individual_count is null or individual_count >= 0),
  behaviour text,

  -- location (precise coordinates stay private)
  district text,
  state text,
  country text default 'India',
  latitude double precision,
  longitude double precision,
  location_precision text not null default 'district'
    check (location_precision in ('precise_private', 'district', 'region', 'hidden')),
  public_location_precision text not null default 'district',
  public_location_label text,
  sensitivity_level text not null default 'normal'
    check (sensitivity_level in ('normal', 'elevated', 'high', 'critical')),
  sensitivity_source text default 'auto',
  breeding_site boolean not null default false,

  -- editorial verification
  verification_status text not null default 'user_reported'
    check (verification_status in ('unverified', 'user_reported', 'ai_suggestion',
                                   'editor_verified', 'scientifically_verified')),
  ai_suggested_species text,
  ai_suggestion_note text,
  editor_notes text,
  rejection_reason text,
  info_request_message text,

  -- publication / curation
  featured boolean not null default false,
  editorial_priority integer not null default 10,
  is_published boolean not null default false,
  published_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,

  -- contributor attribution & privacy
  contributor_display_name text,
  contributor_privacy text not null default 'named'
    check (contributor_privacy in ('named', 'anonymous')),

  -- abuse / moderation
  is_flagged boolean not null default false,
  flag_reason text,
  content_hash text,
  duplicate_of uuid references public.wildlife_sightings(id) on delete set null,
  submission_source text default 'app'
);

