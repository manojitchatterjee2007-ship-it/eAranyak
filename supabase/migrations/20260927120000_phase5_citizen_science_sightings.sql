-- Editorial guard: server-authoritative status, editorial-field protection,
-- sensitivity masking, rate limiting, publication sync and de-duplication.
create or replace function public.wildlife_sightings_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_is_editor boolean := public.is_editor();
  v_uid uuid := auth.uid();
  v_recent integer;
  v_last timestamptz;
begin
  if coalesce(auth.jwt() ->> 'role', '') = 'service_role'
     or coalesce(current_setting('role', true), '') = 'service_role'
     or coalesce(current_setting('earanyak.system_write', true), '') = 'on' then
    null; -- Automation / service role / vetted definer RPC is trusted.
  elsif tg_op = 'INSERT' then
    if not v_is_editor then
      if v_uid is null then
        raise exception 'লগইন আবশ্যক / Authentication required';
      end if;

      -- Abuse protection: max 20 submissions per rolling 24h, 10s minimum gap.
      select count(*) into v_recent
        from public.wildlife_sightings
       where user_id = v_uid and submitted_at > now() - interval '24 hours';
      if v_recent >= 20 then
        insert into public.wildlife_sighting_audit_log (actor_id, actor_role, action, details)
        values (v_uid, 'user', 'rate_limit_blocked',
                jsonb_build_object('window', '24h', 'count', v_recent));
        raise exception 'একদিনে অনেকগুলি জমা হয়ে গেছে — অনুগ্রহ করে পরে আবার চেষ্টা করুন। / Daily submission limit reached.';
      end if;

      select max(submitted_at) into v_last
        from public.wildlife_sightings where user_id = v_uid;
      if v_last is not null and v_last > now() - interval '10 seconds' then
        insert into public.wildlife_sighting_audit_log (actor_id, actor_role, action, details)
        values (v_uid, 'user', 'rate_limit_blocked', jsonb_build_object('window', '10s'));
        raise exception 'একটু ধীরে — কয়েক সেকেন্ড পরে আবার পাঠান। / Please try again in a few seconds.';
      end if;

      NEW.user_id := v_uid;
      NEW.sensitivity_source := 'auto';
      NEW.duplicate_of := null;
      NEW.reviewed_by := null;
      NEW.reviewed_at := null;
      NEW.editor_notes := null;
      NEW.rejection_reason := null;
      NEW.info_request_message := null;
      NEW.ai_suggested_species := null;
      NEW.ai_suggestion_note := null;
      NEW.featured := false;
      NEW.editorial_priority := 10;
      NEW.is_flagged := false;
      NEW.status := case when NEW.status in ('draft', 'submitted') then NEW.status else 'submitted' end;
    end if;
  else
    -- UPDATE
    if not v_is_editor then
      if v_uid is null or OLD.user_id is distinct from v_uid then
        raise exception 'এই রেকর্ড পরিবর্তনের অনুমতি নেই / Not permitted to modify this record';
      end if;
      if OLD.status not in ('draft', 'submitted', 'needs_information') then
        raise exception 'পর্যালোচনা শুরু হওয়ার পরে জমা আর সম্পাদনা করা যায় না / This sighting can no longer be edited';
      end if;

      NEW.user_id := OLD.user_id;
      NEW.status := case when NEW.status in ('draft', 'submitted') then NEW.status else OLD.status end;
      NEW.sensitivity_source := OLD.sensitivity_source;
      NEW.duplicate_of := OLD.duplicate_of;
      NEW.reviewed_by := OLD.reviewed_by;
      NEW.reviewed_at := OLD.reviewed_at;
      NEW.editor_notes := OLD.editor_notes;
      NEW.rejection_reason := OLD.rejection_reason;
      NEW.info_request_message := OLD.info_request_message;
      NEW.ai_suggested_species := OLD.ai_suggested_species;
      NEW.ai_suggestion_note := OLD.ai_suggestion_note;
      NEW.verification_status := OLD.verification_status;
      NEW.featured := OLD.featured;
      NEW.editorial_priority := OLD.editorial_priority;
      NEW.is_flagged := OLD.is_flagged;
      NEW.flag_reason := OLD.flag_reason;
      NEW.published_at := OLD.published_at;
      NEW.content_hash := OLD.content_hash;
    else
      NEW.user_id := coalesce(NEW.user_id, OLD.user_id);
    end if;
  end if;

  -- Normalise and validate required content.
  NEW.common_name := nullif(btrim(coalesce(NEW.common_name, '')), '');
  if NEW.common_name is null then
    raise exception 'প্রজাতির নাম আবশ্যক / Species name is required';
  end if;
  NEW.bengali_name := nullif(btrim(coalesce(NEW.bengali_name, '')), '');
  NEW.scientific_name := nullif(btrim(coalesce(NEW.scientific_name, '')), '');
  NEW.description := nullif(btrim(coalesce(NEW.description, '')), '');
  NEW.district := nullif(btrim(coalesce(NEW.district, '')), '');
  NEW.state := nullif(btrim(coalesce(NEW.state, '')), '');
  NEW.country := coalesce(nullif(btrim(coalesce(NEW.country, '')), ''), 'India');

  if NEW.observed_at is null then NEW.observed_at := current_date; end if;
  if NEW.observed_at > current_date then NEW.observed_at := current_date; end if;

  if NEW.latitude is not null and (NEW.latitude < -90 or NEW.latitude > 90) then
    raise exception 'অবৈধ অক্ষাংশ / Invalid latitude';
  end if;
  if NEW.longitude is not null and (NEW.longitude < -180 or NEW.longitude > 180) then
    raise exception 'অবৈধ দ্রাঘিমাংশ / Invalid longitude';
  end if;

  -- Sensitivity: IUCN threat categories and breeding sites auto-mask.
  if v_is_editor and NEW.sensitivity_source = 'editor' then
    null; -- editorial override respected
  else
    NEW.sensitivity_level :=
      public.infer_sighting_sensitivity(NEW.iucn_status, NEW.sensitivity_level);
  end if;
  if coalesce(NEW.breeding_site, false) then
    NEW.sensitivity_level := 'critical';
    NEW.sensitivity_source := 'breeding_site';
  end if;

  NEW.public_location_precision :=
    public.effective_sighting_precision(NEW.location_precision, NEW.sensitivity_level);

  -- Editors may override the public label; everyone else gets the masked label.
  if v_is_editor
     and nullif(btrim(coalesce(NEW.public_location_label, '')), '') is not null
     and (tg_op = 'INSERT'
          or NEW.public_location_label is distinct from OLD.public_location_label) then
    NEW.public_location_label := btrim(NEW.public_location_label);
  else
    NEW.public_location_label := public.build_public_location_label(
      NEW.district, NEW.state, NEW.country, NEW.location_precision, NEW.sensitivity_level);
  end if;

  -- Server-authoritative publication state.
  NEW.is_published := (NEW.status = 'published');
  if NEW.is_published then
    NEW.published_at := coalesce(NEW.published_at, now());
  end if;

  if tg_op = 'INSERT' then
    NEW.submitted_at := coalesce(NEW.submitted_at, now());
  else
    if NEW.status is distinct from OLD.status and v_is_editor then
      NEW.reviewed_at := now();
      NEW.reviewed_by := coalesce(v_uid, OLD.reviewed_by);
    end if;
    if NEW.status = 'submitted' and OLD.status in ('draft', 'needs_information') then
      NEW.submitted_at := now();
    end if;
  end if;

  NEW.content_hash := public.build_sighting_content_hash(
    NEW.common_name, NEW.bengali_name, NEW.scientific_name, NEW.observed_at, NEW.district);

  if NEW.duplicate_of is null and NEW.content_hash is not null then
    select s.id into NEW.duplicate_of
      from public.wildlife_sightings s
     where s.user_id is not distinct from coalesce(NEW.user_id, v_uid)
       and s.content_hash = NEW.content_hash
       and s.id is distinct from NEW.id
       and s.status <> 'rejected'
     order by s.created_at desc
     limit 1;
  end if;

  NEW.updated_at := now();
  return NEW;
end;
$$;

-- After-change: append-only audit trail, contributor notifications (written by
-- the database so they cannot be forged by clients) and media visibility sync.
create or replace function public.wildlife_sightings_after_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor uuid := auth.uid();
  v_role text := case
    when public.is_editor() then 'editor'
    when auth.uid() is null then 'system'
    else 'user' end;
  v_name text := coalesce(nullif(NEW.bengali_name, ''), nullif(NEW.common_name, ''), 'দর্শন');
  v_kind text;
  v_title text;
  v_body text;
begin
  if tg_op = 'INSERT' then
    insert into public.wildlife_sighting_audit_log
      (sighting_id, actor_id, actor_role, action, to_status, details)
    values (NEW.id, coalesce(v_actor, NEW.user_id), v_role,
            case when NEW.status = 'draft' then 'draft_created' else 'submission_received' end,
            NEW.status,
            jsonb_build_object('sensitivity', NEW.sensitivity_level,
                               'duplicate_of', NEW.duplicate_of));

    if NEW.status = 'submitted' and NEW.user_id is not null then
      insert into public.sighting_notifications (user_id, sighting_id, kind, title_bn, body_bn)
      values (NEW.user_id, NEW.id, 'submission_received',
              'আপনার দর্শন জমা হয়েছে 🌿',
              v_name || ' — সম্পাদকীয় পর্যালোচনার জন্য জমা হয়েছে। ধন্যবাদ!');
    end if;

    return null;
  end if;

  -- UPDATE branch
  if NEW.is_published is distinct from OLD.is_published then
    update public.wildlife_sighting_media
       set is_public = NEW.is_published
     where sighting_id = NEW.id;
  end if;

  if NEW.status is distinct from OLD.status then
    insert into public.wildlife_sighting_audit_log
      (sighting_id, actor_id, actor_role, action, from_status, to_status, details)
    values (NEW.id, v_actor, v_role, 'status_change', OLD.status, NEW.status,
            jsonb_build_object('featured', NEW.featured,
                               'verification_status', NEW.verification_status));

    v_kind := case NEW.status
      when 'needs_information' then 'info_requested'
      when 'approved' then 'approved'
      when 'published' then 'published'
      when 'rejected' then 'rejected'
      when 'archived' then 'archived'
      else null end;

    if v_kind is not null and NEW.user_id is not null then
      v_title := case v_kind
        when 'info_requested' then 'আপনার দর্শন সম্পর্কে কিছু তথ্য প্রয়োজন'
        when 'approved' then 'আপনার দর্শন যাচাই হয়েছে ✅'
        when 'published' then 'আপনার দর্শন প্রকাশিত হয়েছে 🌿'
        when 'rejected' then 'আপনার দর্শন প্রকাশ করা হয়নি'
        else 'আপনার দর্শন সংরক্ষণাগারে রাখা হয়েছে' end;

      v_body := case v_kind
        when 'info_requested' then coalesce(
          nullif(btrim(coalesce(NEW.info_request_message, '')), ''),
          'অনুগ্রহ করে আপনার দর্শনের বিবরণ বা ছবি সম্পূর্ণ করুন।')
        when 'approved' then v_name || ' — সম্পাদকীয় যাচাই সম্পূর্ণ হয়েছে।'
        when 'published' then v_name || ' — এখন নাগরিক বিজ্ঞান বিভাগে প্রকাশিত।'
        when 'rejected' then coalesce(
          nullif(btrim(coalesce(NEW.rejection_reason, '')), ''),
          'আপনার জমাটি এই মুহূর্তে প্রকাশের জন্য উপযুক্ত ছিল না।')
        else v_name || ' — আর্কাইভে সংরক্ষিত।' end;

      insert into public.sighting_notifications (user_id, sighting_id, kind, title_bn, body_bn)
      values (NEW.user_id, NEW.id, v_kind, v_title, v_body);
    end if;
  elsif NEW.editor_notes is distinct from OLD.editor_notes
        or NEW.verification_status is distinct from OLD.verification_status
        or NEW.featured is distinct from OLD.featured
        or NEW.public_location_label is distinct from OLD.public_location_label
        or NEW.is_flagged is distinct from OLD.is_flagged then
    insert into public.wildlife_sighting_audit_log
      (sighting_id, actor_id, actor_role, action, from_status, to_status, details)
    values (NEW.id, v_actor, v_role, 'editorial_update', OLD.status, NEW.status,
            jsonb_build_object(
              'verification_status', NEW.verification_status,
              'featured', NEW.featured,
              'public_location_label', NEW.public_location_label,
              'is_flagged', NEW.is_flagged,
              'flag_reason', NEW.flag_reason));
  end if;

  return null;
end;
$$;

-- Media guard: path-traversal safe, MIME/size validated, quota-limited.
create or replace function public.wildlife_sighting_media_guard()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_is_editor boolean := public.is_editor();
  v_uid uuid := auth.uid();
  v_sighting public.wildlife_sightings%rowtype;
  v_count integer;
  v_limit integer;
  v_max_bytes bigint;
  v_allowed_mime text[] := array[
    'image/jpeg', 'image/jpg', 'image/png', 'image/webp',
    'audio/mpeg', 'audio/mp3', 'audio/mp4', 'audio/wav', 'audio/x-wav', 'audio/ogg',
    'video/mp4', 'video/quicktime', 'video/webm'];
begin
  select * into v_sighting
    from public.wildlife_sightings s where s.id = NEW.sighting_id;

  if v_sighting.id is null then
    raise exception 'দর্শনটি পাওয়া যায়নি / Sighting not found';
  end if;

  if not v_is_editor then
    if v_uid is null or v_sighting.user_id is distinct from v_uid then
      raise exception 'অনুমতি নেই / Not permitted';
    end if;
    if v_sighting.status not in ('draft', 'submitted', 'needs_information') then
      raise exception 'পর্যালোচনার পরে ফাইল যোগ করা যায় না / Media can no longer be added';
    end if;
    NEW.user_id := v_uid;
  else
    NEW.user_id := coalesce(NEW.user_id, v_sighting.user_id);
  end if;

  NEW.media_type := lower(btrim(coalesce(NEW.media_type, 'photo')));
  if NEW.media_type not in ('photo', 'audio', 'video') then
    raise exception 'অসমর্থিত ফাইল ধরন / Unsupported media type';
  end if;

  NEW.bucket_id := coalesce(nullif(btrim(coalesce(NEW.bucket_id, '')), ''), 'citizen_sightings');
  if NEW.bucket_id <> 'citizen_sightings' then
    raise exception 'অসমর্থিত স্টোরেজ / Unsupported bucket';
  end if;

  -- Storage path must be exactly {user_id}/{sighting_id}/{safe-filename}
  NEW.storage_path := btrim(coalesce(NEW.storage_path, ''));
  if NEW.storage_path = ''
     or position('..' in NEW.storage_path) > 0
     or position('\' in NEW.storage_path) > 0
     or left(NEW.storage_path, 1) = '/'
     or position('//' in NEW.storage_path) > 0
     or NEW.storage_path !~ '^[0-9a-fA-F-]{36}/[0-9a-fA-F-]{36}/[A-Za-z0-9._-]+$' then
    raise exception 'অবৈধ ফাইল পাথ / Invalid storage path';
  end if;

  if split_part(NEW.storage_path, '/', 2) <> NEW.sighting_id::text then
    raise exception 'অবৈধ ফাইল অবস্থান / Invalid media location';
  end if;
  if split_part(NEW.storage_path, '/', 1) <> coalesce(v_sighting.user_id::text, v_uid::text) then
    raise exception 'অবৈধ ফাইল অবস্থান / Invalid media owner folder';
  end if;

  NEW.mime_type := lower(btrim(coalesce(NEW.mime_type, '')));
  if NEW.mime_type <> '' and not (NEW.mime_type = any (v_allowed_mime)) then
    raise exception 'অসমর্থিত ফাইল ফরম্যাট / Unsupported file format';
  end if;

  v_max_bytes := case NEW.media_type
    when 'photo' then 15728640      -- 15 MB
    when 'audio' then 26214400      -- 25 MB
    else 104857600 end;             -- 100 MB video
  if NEW.file_size_bytes is not null and NEW.file_size_bytes > v_max_bytes then
    raise exception 'ফাইলটি অনেক বড় / File exceeds the size limit';
  end if;

  select count(*) into v_count
    from public.wildlife_sighting_media m
   where m.sighting_id = NEW.sighting_id
     and m.media_type = NEW.media_type
     and m.id is distinct from NEW.id;
  v_limit := case NEW.media_type when 'photo' then 8 when 'audio' then 2 else 2 end;
  if v_count >= v_limit then
    raise exception 'এই দর্শনে আরও ফাইল যোগ করা যাবে না / Media limit reached';
  end if;

  NEW.caption := nullif(btrim(coalesce(NEW.caption, '')), '');
  NEW.display_order := coalesce(NEW.display_order, 0);
  NEW.is_public := (v_sighting.status = 'published' and v_sighting.is_published);
  return NEW;
end;
$$;

