-- =============================================================================
-- eআরণ্যক / eAranyak
-- Phase 5: Citizen Science / Wildlife Sightings
-- Schema + RLS + Indexes + Triggers + Public Views + Storage Bucket + RPCs
--
-- Design notes
--  * Additive & idempotent. Phase 4 (daily_wildlife_features / about_us_content),
--    the wildlife_gallery architecture and every existing content-protection
--    mechanism are left untouched.
--  * Precise coordinates live ONLY in public.wildlife_sightings, whose SELECT
--    policies exclude anon/public. Public screens read the masked projection
--    public.public_wildlife_sightings (coordinates are not columns there).
--  * Publication state is server-authoritative: a BEFORE trigger on the table
--    forces is_published = (status = 'published') and restores every editorial
--    column for non-editor writers, so the client can never bypass review.
--  * Sensitive species are masked server-side (IUCN threat categories and
--    breeding/nest/roost sites) before any public label is derived.
--  * Every state transition is written to an append-only audit log, and
--    contributor notifications are generated by the database (tamper-proof).
-- =============================================================================

begin;

